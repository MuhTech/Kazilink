type Dict = Record<string, any>;

const dicts: Record<string, Dict> = {
  en: dict.en,
  sw: dict.sw,
  fr: {
    ...dict.en,
    brand: "KaziLink Tanzania",
    tagline: "Connecter les compétences aux opportunités",
  },
  ar: { ...dict.en, brand: "KaziLink Tanzania" },
  es: { ...dict.en, brand: "KaziLink Tanzania" },
  pt: { ...dict.en, brand: "KaziLink Tanzania" },
  zh: { ...dict.en, brand: "KaziLink Tanzania" },
  de: { ...dict.en, brand: "KaziLink Tanzania" },
};

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: "en",
  setLang: () => {},
  t: dict.en,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved =
      (typeof window !== "undefined" && (localStorage.getItem("kazilink.lang") as Lang | null)) ||
      null;
    if (saved && dicts[saved]) {
      setLangState(saved);
    }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("kazilink.lang", l);
  };

  const activeDict = dicts[lang] || dict.en;

  return <LangCtx.Provider value={{ lang, setLang, t: activeDict }}>{children}</LangCtx.Provider>;
}

export function useT() {
  const context = useContext(LangCtx);
  if (!context || !context.t) {
    return { lang: "en" as Lang, setLang: () => {}, t: dict.en };
  }
  return context;
}
